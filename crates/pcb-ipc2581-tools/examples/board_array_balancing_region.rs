use serde::Serialize;

const SCHEMA: &str = "pcb-ir.board-array-balancing-debug.v9";
const DEFAULT_CHECK_AREA_TOLERANCE_MM2: f64 = 1e-4;
const SVG_PADDING_MM: f64 = 2.0;
const SVG_STROKE_MM: f64 = 0.12;

#[derive(Debug, Parser)]
#[command(
    about = "Derive and inspect the copper-balancing-safe region of an IPC-2581 board array",
    long_about = "Development harness that emits every intermediate planar region, a toggleable HTML/SVG overlay, per-layer support-feature views, and clearance-certificate checks."
)]
struct Args {
    /// Board-array IPC-2581 XML (plain or .zst).
    input: PathBuf,

    /// Directory to receive deterministic debug artifacts.
    #[arg(short, long)]
    output: PathBuf,

    /// Required Euclidean clearance from the panel boundary and every obstacle.
    #[arg(long, default_value_t = DEFAULT_BALANCING_CLEARANCE_MM)]
    clearance_mm: f64,

    /// Disk radius used to round filled-region corners and reject small regions or slivers.
    #[arg(long, default_value_t = DEFAULT_BALANCING_REGULARIZATION_RADIUS_MM)]
    regularization_radius_mm: f64,

    /// Rolling-disk radius for two-sided void gaps; minimum gap is twice this.
    #[arg(long, default_value_t = DEFAULT_BALANCING_GAP_RADIUS_MM)]
    gap_radius_mm: f64,

    /// Extra construction clearance reserved for polygonization/offset error.
    #[arg(long, default_value_t = DEFAULT_BALANCING_NUMERICAL_GUARD_MM)]
    numerical_guard_mm: f64,

    /// Maximum tolerated area for each set-theoretic validation violation.
    #[arg(long, default_value_t = DEFAULT_CHECK_AREA_TOLERANCE_MM2)]
    check_area_tolerance_mm2: f64,

    /// Reject inputs not generated by the A-series auto panelizer.
    #[arg(long)]
    require_a_series_auto: bool,

    /// Copper layer to inspect. Defaults to the first copper layer in the IPC.
    #[arg(long)]
    copper_layer: Option<String>,
}

