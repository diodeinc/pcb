#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
struct PanelizationJson {
    mode: Option<String>,
    sheet: Option<String>,
    columns: Option<u32>,
    rows: Option<u32>,
}

impl PanelizationJson {
    fn from_xml(xml: &str) -> Self {
        Self {
            mode: generated_metadata_value(xml, "diode.panelize.mode"),
            sheet: generated_metadata_value(xml, "diode.panelize.sheet"),
            columns: generated_metadata_value(xml, "diode.panelize.columns")
                .and_then(|value| value.parse().ok()),
            rows: generated_metadata_value(xml, "diode.panelize.rows")
                .and_then(|value| value.parse().ok()),
        }
    }

    fn is_a_series_auto(&self) -> bool {
        matches!(self.mode.as_deref(), Some("auto" | "auto_sheet"))
            && matches!(self.sheet.as_deref(), Some("A7" | "A6" | "A5" | "A4"))
    }
}

