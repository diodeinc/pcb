#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
struct RegionJson {
    area_mm2: f64,
    ring_count: usize,
    vertex_count: usize,
    bbox_mm: Option<BBoxJson>,
    rings_mm: Vec<Vec<[f64; 2]>>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
struct BBoxJson {
    min: [f64; 2],
    max: [f64; 2],
}

impl From<&ContourSet> for RegionJson {
    fn from(region: &ContourSet) -> Self {
        Self {
            area_mm2: region.area(),
            ring_count: region.rings.len(),
            vertex_count: region.rings.iter().map(Vec::len).sum(),
            bbox_mm: (!region.bbox.is_empty()).then_some(BBoxJson {
                min: [region.bbox.min.x, region.bbox.min.y],
                max: [region.bbox.max.x, region.bbox.max.y],
            }),
            rings_mm: region.rings.clone(),
        }
    }
}

fn component_areas(region: &ContourSet) -> Vec<f64> {
    region
        .connected_components()
        .into_iter()
        .map(|component| component.area())
        .collect()
}

fn main() -> Result<()> {
    let accuracy = GeometryAccuracy::default();

    let args = Args::parse();
    // The radius and clearance options are validated by
    // `board_array_balancing_region` itself.
    if !args.check_area_tolerance_mm2.is_finite() || args.check_area_tolerance_mm2 < 0.0 {
        bail!("--check-area-tolerance-mm2 must be a finite non-negative number");
    }

    let input = args
        .input
        .canonicalize()
        .with_context(|| format!("failed to resolve input {}", args.input.display()))?;
    let xml = load_ipc_file(&input)?;
    let panelization = PanelizationJson::from_xml(&xml);
    if args.require_a_series_auto && !panelization.is_a_series_auto() {
        bail!(
            "input is not an A-series auto-panelized array (mode {:?}, sheet {:?})",
            panelization.mode,
            panelization.sheet
        );
    }
    let ipc = Ipc2581::parse(&xml).context("failed to parse IPC-2581 input")?;
    let ecad = ipc.ecad().context("IPC-2581 file has no ECAD section")?;
    let copper_layers = copper_layers(ecad);
    let selected_copper = match &args.copper_layer {
        Some(requested) => copper_layers
            .iter()
            .find(|layer| ipc.resolve(layer.name) == requested)
            .with_context(|| format!("copper layer '{requested}' was not found"))?,
        None => copper_layers
            .first()
            .context("IPC-2581 file has no copper layers")?,
    };
    let selected_copper_name = ipc.resolve(selected_copper.name).to_string();
    let layout = extract_layout(&ipc).context("failed to extract IPC layout graph")?;
    if root_panel_step(&layout).is_none() {
        bail!("input is not a board array: the IPC root step is not a panel");
    }

    let score_lines = board_array_vscore_lines(&ipc, accuracy)
        .context("failed to extract board-array V-score lines")?;
    let (fabrication_profile, relief_debug) =
        board_array_fabrication_profile_with_debug(&ipc, &layout, &score_lines, accuracy)
            .context("failed to compose board-array fabrication profile")?;

    let support_sources = extract_array_support_layers(&ipc, accuracy)?;
    let collection = inspect_board_array_balancing_input(
        &layout,
        &fabrication_profile,
        &copper_layers,
        support_sources
            .iter()
            .map(|source| BoardArraySupportDocument::new(&source.document, source.policy)),
        accuracy,
    )
    .context("failed to collect board-array balancing inputs")?;
    let balancing_input = collection.input_for_layer(selected_copper.name);
    let options = BalancingRegionOptions {
        clearance_mm: args.clearance_mm,
        regularization_radius_mm: args.regularization_radius_mm,
        gap_radius_mm: args.gap_radius_mm,
        numerical_guard_mm: args.numerical_guard_mm,
    };
    let result = board_array_balancing_region(&balancing_input, options, accuracy)
        .context("failed to compute board-array balancing region")?;
    let construction_clearance_mm = options.construction_clearance_mm();
    let certificate_passed = result.certificate.passes(args.check_area_tolerance_mm2);
    let support_features = balancing_input.support_features;
    let panel_outer = collection.panel_outer;
    let board_footprints = collection.board_footprints;
    let material_removal = collection.material_removal;
    let board_instances = collection.board_instance_count;
    let support_geometry = collection.support_layers;
    let support_layers = support_sources
        .into_iter()
        .zip(support_geometry)
        .map(|(source, geometry)| support_layer(source, geometry, selected_copper.name))
        .collect::<Vec<_>>();
    let BoardArrayBalancingResult {
        safe_region,
        intermediates,
        certificate,
    } = result;
    let final_components = safe_region.connected_components();
    let undersized_final_components = final_components
        .iter()
        .filter(|component| {
            component
                .disk_erode(args.regularization_radius_mm, accuracy)
                .unwrap()
                .is_empty()
        })
        .cloned()
        .fold(
            ContourSet::empty(safe_region.tolerance),
            |undersized, component| undersized.union(&component),
        );
    let removed_by_regularization = intermediates
        .removed_by_opening
        .union(&intermediates.removed_by_gap_regularization);
    let narrow_voids = intermediates
        .opened_candidates
        .disk_gap_violations(args.gap_radius_mm, accuracy)
        .unwrap();
    let regions = Regions {
        panel_outer,
        board_footprints,
        material_removal,
        support_features,
        raw_obstacles: intermediates.raw_obstacles,
        panel_keep_in: intermediates.panel_keep_in,
        obstacle_keep_out: intermediates.obstacle_keep_out,
        clearance_safe_region: intermediates.clearance_safe_region,
        opened_candidates: intermediates.opened_candidates,
        removed_by_opening: intermediates.removed_by_opening,
        narrow_voids,
        removed_by_gap_regularization: intermediates.removed_by_gap_regularization,
        removed_by_regularization,
        safe_region,
        undersized_final_components,
        clearance_certificate: certificate.swept_safe_region,
        safe_outside_clearance_region: certificate.safe_outside_clearance_region,
        regularization_violations: certificate.regularization_violations,
        gap_violations: certificate.gap_violations,
        certificate_outside_panel: certificate.outside_panel,
        certificate_obstacle_overlap: certificate.obstacle_overlap,
    };

    let checks = ChecksJson {
        passed: certificate_passed,
        safe_outside_clearance_region_area_mm2: regions.safe_outside_clearance_region.area(),
        regularization_violation_area_mm2: regions.regularization_violations.area(),
        gap_violation_area_mm2: regions.gap_violations.area(),
        certificate_outside_panel_area_mm2: regions.certificate_outside_panel.area(),
        certificate_obstacle_overlap_area_mm2: regions.certificate_obstacle_overlap.area(),
    };
    let clearance_safe_component_areas = component_areas(&regions.clearance_safe_region);
    let opened_component_areas = component_areas(&regions.opened_candidates);
    let final_component_areas = final_components
        .iter()
        .map(ContourSet::area)
        .collect::<Vec<_>>();
    let minimum_final_component_bbox_span_mm = final_components
        .iter()
        .map(|component| component.bbox.width().min(component.bbox.height()))
        .reduce(f64::min);
    let clearance_safe_area_mm2 = regions.clearance_safe_region.area();
    let final_safe_area_mm2 = regions.safe_region.area();
    let regularization = RegularizationJson {
        clearance_safe_area_mm2,
        final_safe_area_mm2,
        removed_area_mm2: regions.removed_by_regularization.area(),
        removed_by_opening_area_mm2: regions.removed_by_opening.area(),
        narrow_void_area_mm2: regions.narrow_voids.area(),
        removed_by_gap_regularization_area_mm2: regions.removed_by_gap_regularization.area(),
        retained_fraction: if clearance_safe_area_mm2 > 0.0 {
            final_safe_area_mm2 / clearance_safe_area_mm2
        } else {
            1.0
        },
        clearance_safe_component_count: clearance_safe_component_areas.len(),
        opened_component_count: opened_component_areas.len(),
        final_component_count: final_component_areas.len(),
        smallest_final_component_area_mm2: final_component_areas.into_iter().reduce(f64::min),
        minimum_final_component_bbox_span_mm,
        undersized_final_component_count: regions
            .undersized_final_components
            .connected_components()
            .len(),
    };

    let unpainted_support_paths = support_layers
        .iter()
        .map(|layer| layer.unpainted_path_count)
        .sum::<usize>();
    let passed = checks.passed
        && unpainted_support_paths == 0
        && regularization.undersized_final_component_count == 0;
    let artifact = DebugArtifact {
        schema: SCHEMA,
        passed,
        input: input.display().to_string(),
        copper_layer: selected_copper_name,
        nominal_clearance_mm: args.clearance_mm,
        regularization_radius_mm: args.regularization_radius_mm,
        gap_radius_mm: args.gap_radius_mm,
        numerical_guard_mm: args.numerical_guard_mm,
        construction_clearance_mm,
        check_area_tolerance_mm2: args.check_area_tolerance_mm2,
        panelization,
        counts: CountsJson {
            board_instances,
            source_layers: support_layers.len(),
            source_support_features: support_layers
                .iter()
                .map(|layer| layer.source_feature_count)
                .sum(),
            support_features: support_layers.iter().map(|layer| layer.feature_count).sum(),
            source_support_paths: support_layers
                .iter()
                .map(|layer| layer.source_path_count)
                .sum(),
            support_paths: support_layers.iter().map(|layer| layer.path_count).sum(),
            excluded_documentation_paths: support_layers
                .iter()
                .map(|layer| layer.excluded_documentation_path_count)
                .sum(),
            vscore_lines: score_lines.len(),
            vscore_relief_entries: relief_debug.entries.len(),
        },
        coverage: CoverageJson {
            complete: unpainted_support_paths == 0,
            unpainted_support_paths,
            note: "Every painted ArraySupport path is assigned once from its IR feature span: exact copper and adjacent-surface geometry affect that copper layer, while through-stack or unresolved physical geometry affects all copper layers. Same-layer V-cut arrows and labels are excluded by the V_Cut process specification. Unpainted included paths have no defined physical envelope and are reported as incomplete coverage.",
        },
        regularization,
        checks,
        support_layers: support_layers
            .iter()
            .map(|layer| SupportLayerJson {
                name: layer.name.clone(),
                function: layer.function.clone(),
                source_feature_count: layer.source_feature_count,
                feature_count: layer.feature_count,
                source_path_count: layer.source_path_count,
                path_count: layer.path_count,
                excluded_documentation_path_count: layer.excluded_documentation_path_count,
                unpainted_path_count: layer.unpainted_path_count,
                region: RegionJson::from(&layer.region),
            })
            .collect(),
        regions: RegionsJson {
            panel_outer: RegionJson::from(&regions.panel_outer),
            board_footprints: RegionJson::from(&regions.board_footprints),
            material_removal: RegionJson::from(&regions.material_removal),
            support_features: RegionJson::from(&regions.support_features),
            raw_obstacles: RegionJson::from(&regions.raw_obstacles),
            panel_keep_in: RegionJson::from(&regions.panel_keep_in),
            obstacle_keep_out: RegionJson::from(&regions.obstacle_keep_out),
            clearance_safe_region: RegionJson::from(&regions.clearance_safe_region),
            opened_candidates: RegionJson::from(&regions.opened_candidates),
            removed_by_opening: RegionJson::from(&regions.removed_by_opening),
            narrow_voids: RegionJson::from(&regions.narrow_voids),
            removed_by_gap_regularization: RegionJson::from(&regions.removed_by_gap_regularization),
            removed_by_regularization: RegionJson::from(&regions.removed_by_regularization),
            safe_region: RegionJson::from(&regions.safe_region),
            undersized_final_components: RegionJson::from(&regions.undersized_final_components),
            clearance_certificate: RegionJson::from(&regions.clearance_certificate),
            safe_outside_clearance_region: RegionJson::from(&regions.safe_outside_clearance_region),
            regularization_violations: RegionJson::from(&regions.regularization_violations),
            gap_violations: RegionJson::from(&regions.gap_violations),
            certificate_outside_panel: RegionJson::from(&regions.certificate_outside_panel),
            certificate_obstacle_overlap: RegionJson::from(&regions.certificate_obstacle_overlap),
        },
    };

    write_artifacts(&args.output, &input, &regions, &support_layers, &artifact)?;

    println!("wrote {}", args.output.join("index.html").display());
    println!(
        "safe area: {:.3} mm² ({:.1}% of the {:.3} mm² panel)",
        regions.safe_region.area(),
        100.0 * regions.safe_region.area() / regions.panel_outer.area(),
        regions.panel_outer.area()
    );
    println!(
        "regularization: {:.3} mm region radius, {:.3} mm gap radius retained {:.3} / {:.3} mm² ({:.1}%, {} clearance-safe -> {} opened -> {} final components, {} undersized)",
        artifact.regularization_radius_mm,
        artifact.gap_radius_mm,
        artifact.regularization.final_safe_area_mm2,
        artifact.regularization.clearance_safe_area_mm2,
        100.0 * artifact.regularization.retained_fraction,
        artifact.regularization.clearance_safe_component_count,
        artifact.regularization.opened_component_count,
        artifact.regularization.final_component_count,
        artifact.regularization.undersized_final_component_count,
    );
    println!(
        "coverage: {} ({} unpainted support paths)",
        if artifact.coverage.complete {
            "complete"
        } else {
            "incomplete"
        },
        artifact.coverage.unpainted_support_paths
    );
    println!(
        "certificate: {} (outside clearance-safe region {:.6} mm², regularization violations {:.6} mm², void-gap violations {:.6} mm², outside panel {:.6} mm², obstacle overlap {:.6} mm²)",
        if artifact.checks.passed {
            "PASS"
        } else {
            "FAIL"
        },
        artifact.checks.safe_outside_clearance_region_area_mm2,
        artifact.checks.regularization_violation_area_mm2,
        artifact.checks.gap_violation_area_mm2,
        artifact.checks.certificate_outside_panel_area_mm2,
        artifact.checks.certificate_obstacle_overlap_area_mm2,
    );

    if !artifact.passed {
        bail!(
            "balancing-region validation failed; debug artifacts were written to {}",
            args.output.display()
        );
    }

    Ok(())
}

fn support_layer(
    source: ArraySupportLayerSource,
    geometry: BoardArraySupportLayerGeometry<Symbol>,
    copper_layer: Symbol,
) -> SupportLayer {
    SupportLayer {
        name: source.name,
        function: layer_function_name(source.layer_function),
        source_feature_count: geometry.source_feature_count,
        feature_count: geometry.feature_count,
        source_path_count: geometry.source_path_count,
        path_count: geometry.path_count,
        excluded_documentation_path_count: geometry.excluded_documentation_path_count,
        unpainted_path_count: geometry.unpainted_path_count,
        region: geometry.region_for_layer(copper_layer),
    }
}

fn layer_function_name(function: LayerFunction) -> String {
    format!("{function:?}")
}

fn generated_metadata_value(xml: &str, name: &str) -> Option<String> {
    let marker = format!("name=\"{name}\"");
    let start = xml.find(&marker).unwrap();
    let tag = &xml[start..start + xml[start..].find('>').unwrap()];
    let value_start = tag.find("value=\"").unwrap() + "value=\"".len();
    let value = &tag[value_start..];
    Some(value[..value.find('"').unwrap()].to_string())
}

