fn svg_start(title: &str, bbox: BBox) -> String {
    let bbox = if bbox.is_empty() {
        BBox::new(
            pcb_ir::geom::Point::new(0.0, 0.0),
            pcb_ir::geom::Point::new(1.0, 1.0),
        )
    } else {
        bbox
    };
    let min_x = bbox.min.x - SVG_PADDING_MM;
    let min_y = -(bbox.max.y + SVG_PADDING_MM);
    let width = bbox.width() + 2.0 * SVG_PADDING_MM;
    let height = bbox.height() + 2.0 * SVG_PADDING_MM;
    let mut svg = String::new();
    writeln!(
        svg,
        "<svg xmlns='http://www.w3.org/2000/svg' viewBox='{} {} {} {}' role='img'>",
        num(min_x),
        num(min_y),
        num(width),
        num(height)
    )
    .unwrap();
    writeln!(svg, "  <title>{}</title>", escape_html(title)).unwrap();
    writeln!(
        svg,
        "  <rect x='{}' y='{}' width='{}' height='{}' fill='#ffffff'/>",
        num(min_x),
        num(min_y),
        num(width),
        num(height)
    )
    .unwrap();
    writeln!(
        svg,
        "  <g transform='scale(1 -1)' stroke-width='{}' stroke-linejoin='round' stroke-linecap='round'>",
        num(SVG_STROKE_MM)
    )
    .unwrap();
    svg
}

fn write_region(svg: &mut String, id: &str, region: &ContourSet, attributes: &str) {
    let Some(path) = region_path_data(region) else {
        writeln!(svg, "    <g id='{id}' data-empty='true'/>").unwrap();
        return;
    };
    writeln!(
        svg,
        "    <path id='{id}' d='{path}' {attributes} fill-rule='nonzero'/>"
    )
    .unwrap();
}

fn region_path_data(region: &ContourSet) -> Option<String> {
    let mut data = String::new();
    for ring in &region.rings {
        let Some(([x, y], rest)) = ring.split_first() else {
            continue;
        };
        if !data.is_empty() {
            data.push(' ');
        }
        write!(data, "M{} {}", num(*x), num(*y)).unwrap();
        for [x, y] in rest {
            write!(data, " L{} {}", num(*x), num(*y)).unwrap();
        }
        data.push_str(" Z");
    }
    (!data.is_empty()).then_some(data)
}

